from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pytest
from tests.comparative_benchmark import agent_execution_receipt as aer

AGENT_IDENTITY = {
    "actor_kind": "claude_code_native_tool_using_agent",
    "session_ref": "https://claude.ai/code/session_TEST0000000000000000000000000",
}
TOOL_SURFACE = ["Bash", "Write"]
RESOURCE_BUDGET = {"max_turns": 1, "retries_allowed": 0}


def _write_output(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, *, relative: str, content: bytes
) -> str:
    monkeypatch.setattr(aer, "ROOT", tmp_path)
    target = tmp_path / relative
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(content)
    return relative


def _build(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, *, condition: str, task_key: str
) -> dict[str, Any]:
    relative = f"{condition.lower()}/{task_key}_output.txt"
    content = f"real output for {task_key} under {condition}".encode()
    output_path = _write_output(tmp_path, monkeypatch, relative=relative, content=content)
    return aer.build_agent_execution_receipt(
        agent_identity=AGENT_IDENTITY,
        condition=condition,
        task_key=task_key,
        task_input=f"perform {task_key} for real",
        tool_surface=TOOL_SURFACE,
        resource_budget=RESOURCE_BUDGET,
        output_path=output_path,
        tool_call_events=[
            {
                "tool": "Bash",
                "started_at": "2026-09-17T14:00:00Z",
                "ended_at": "2026-09-17T14:00:01Z",
            }
        ],
    )


def _verify(receipt: dict[str, Any], *, condition: str, task_key: str) -> None:
    aer.verify_agent_execution_receipt(
        receipt,
        expected_agent_identity=AGENT_IDENTITY,
        expected_condition=condition,
        expected_task_key=task_key,
        expected_task_input=f"perform {task_key} for real",
        expected_tool_surface=TOOL_SURFACE,
        expected_resource_budget=RESOURCE_BUDGET,
        expected_output_path=receipt["output_path"],
    )


# --- positive route -------------------------------------------------------------------- #


def test_a_well_formed_receipt_for_the_real_current_output_verifies_clean(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    receipt = _build(tmp_path, monkeypatch, condition="MANOSUBE_PRESENT", task_key="task_a")
    _verify(receipt, condition="MANOSUBE_PRESENT", task_key="task_a")


def test_receipt_id_is_a_real_content_address_recomputed_identically(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    receipt = _build(tmp_path, monkeypatch, condition="MANOSUBE_ABSENT", task_key="task_b")
    assert receipt["receipt_id"] == aer.agent_execution_receipt_id(receipt)
    assert receipt["receipt_id"].startswith("AGENT-RECEIPT-")


