def test_receipt_replay_or_cross_condition_reuse_is_refused(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """``RECEIPT_REPLAY_OR_CROSS_CONDITION_REUSE``: the exact same real receipt admitted for
    ``MANOSUBE_ABSENT`` cannot be replayed to stand in for ``MANOSUBE_PRESENT`` -- it is
    refused by the identical condition check, since a receipt's own condition field is part
    of what it commits to and cannot be reinterpreted by the caller."""

    absent_receipt = _build(tmp_path, monkeypatch, condition="MANOSUBE_ABSENT", task_key="task_a")
    with pytest.raises(aer.ConditionMismatchError):
        aer.verify_agent_execution_receipt(
            absent_receipt,
            expected_agent_identity=AGENT_IDENTITY,
            expected_condition="MANOSUBE_PRESENT",
            expected_task_key="task_a",
            expected_task_input="perform task_a for real",
            expected_tool_surface=TOOL_SURFACE,
            expected_resource_budget=RESOURCE_BUDGET,
            expected_output_path=absent_receipt["output_path"],
        )


