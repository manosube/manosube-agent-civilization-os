def test_plain_python_callback_as_agent_is_not_a_receipt_shape(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """``PLAIN_PYTHON_CALLBACK_AS_AGENT``: the verifier's own API takes a receipt mapping,
    never a callable -- passing a bare function where a receipt is expected fails structurally
    (no ``.get`` on a function), proving the API shape itself refuses the P90-R6-IF1 defect
    rather than merely documenting against it."""

    def _callback() -> None:
        raise AssertionError("must never be called: callbacks are not receipts")

    with pytest.raises(AttributeError):
        aer.verify_agent_execution_receipt(
            _callback,  # type: ignore[arg-type]
            expected_agent_identity=AGENT_IDENTITY,
            expected_condition="MANOSUBE_PRESENT",
            expected_task_key="task_a",
            expected_task_input="perform task_a for real",
            expected_tool_surface=TOOL_SURFACE,
            expected_resource_budget=RESOURCE_BUDGET,
            expected_output_path="present/task_a_output.txt",
        )


def test_preexisting_output_without_execution_receipt_is_refused(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """``PREEXISTING_OUTPUT_WITHOUT_EXECUTION_RECEIPT``: a real output file exists on disk,
    but no receipt file names it -- :func:`aer.load_receipt` refuses fail-closed rather than
    treating the bare file as proof of a real Agent action."""

    relative = _write_output(
        tmp_path,
        monkeypatch,
        relative="present/task_a_output.txt",
        content=b"looks real but has no receipt",
    )
    with pytest.raises(aer.ReceiptNotFoundError):
        aer.load_receipt(relative + ".receipt.json")


