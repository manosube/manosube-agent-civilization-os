def test_receipt_output_digest_mismatch_is_refused_when_file_changes_after_the_receipt(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """``RECEIPT_OUTPUT_DIGEST_MISMATCH``: the file is modified after the receipt was built --
    verification re-reads the real, current bytes and refuses, never trusting the receipt's
    own self-reported digest alone."""

    receipt = _build(tmp_path, monkeypatch, condition="MANOSUBE_PRESENT", task_key="task_a")
    (tmp_path / receipt["output_path"]).write_bytes(b"tampered after the receipt was built")
    with pytest.raises(aer.OutputDigestMismatchError):
        _verify(receipt, condition="MANOSUBE_PRESENT", task_key="task_a")


def test_receipt_output_digest_mismatch_is_refused_when_the_receipt_itself_is_tampered(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """A hand-edited receipt whose ``output_sha256`` field is changed to match a different
    file, without recomputing ``receipt_id``, is caught first by the integrity check -- a
    receipt cannot be forged by editing one field in isolation."""

    receipt = _build(tmp_path, monkeypatch, condition="MANOSUBE_PRESENT", task_key="task_a")
    receipt["output_sha256"] = "0" * 64
    with pytest.raises(aer.ReceiptIntegrityError):
        _verify(receipt, condition="MANOSUBE_PRESENT", task_key="task_a")


def test_load_receipt_round_trips_a_real_published_receipt_file(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    receipt = _build(tmp_path, monkeypatch, condition="MANOSUBE_ABSENT", task_key="task_b")
    receipt_relative = receipt["output_path"] + ".receipt.json"
    (tmp_path / receipt_relative).write_text(json.dumps(receipt), encoding="utf-8")

    loaded = aer.load_receipt(receipt_relative)

    assert loaded == receipt
    _verify(loaded, condition="MANOSUBE_ABSENT", task_key="task_b")
